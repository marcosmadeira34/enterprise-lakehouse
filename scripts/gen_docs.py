"""Generate the parts of the documentation that must never drift from the code:

* ``docs/data_dictionary.md`` from the data contracts, Silver/Bronze lineage fields and Gold model;
* the rule catalog section of ``docs/data_quality.md`` (between the GENERATED markers) from the row-rule
  catalog and the dataset rules.

Usage: ``uv run python scripts/gen_docs.py`` (``--check`` fails if the files are out of date; used in CI).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from lakehouse.config import BusinessRules  # noqa: E402
from lakehouse.contracts import ENTITIES, FkPolicy  # noqa: E402
from lakehouse.pipelines.bronze.job import LINEAGE_FIELDS  # noqa: E402
from lakehouse.pipelines.gold.model import METRICS  # noqa: E402
from lakehouse.pipelines.silver.transform import DERIVED, SILVER_LINEAGE, SPARK_TYPES, row_rule_catalog  # noqa: E402

BEGIN, END = "<!-- BEGIN GENERATED RULES -->", "<!-- END GENERATED RULES -->"

LINEAGE_DOC = {
    "_extra_columns": "JSON map of source columns not in the contract (schema drift captured, not lost).",
    "_corrupt_record": "Raw text of a record Spark could not parse (wrong field count, invalid JSON).",
    "_record_hash": "SHA-256 of the business values as received.",
    "_batch_id": "Batch the record arrived in.",
    "_batch_seq": "Arrival order of the batch (tie-breaker between versions with equal updated_at).",
    "_run_id": "Run that wrote the record.",
    "_source_file": "URI of the landing file.",
    "_source_file_sha256": "Content hash of the landing file (its identity).",
    "_source_format": "csv | json | parquet.",
    "_source_system": "Configured source system name.",
    "_ingested_at": "When Bronze wrote the record (UTC).",
    "_ingestion_date": "Partition column: date the batch was planned.",
    "_silver_run_id": "Run that last merged the record into Silver.",
    "_silver_processed_at": "When the record was last merged (UTC).",
}

