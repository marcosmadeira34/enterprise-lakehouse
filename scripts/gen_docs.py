def data_dictionary() -> str:
    out = [
        "# Data dictionary",
        "",
        "> Generated by `scripts/gen_docs.py` from `src/lakehouse/contracts.py` and the pipeline code. Do not edit by hand.",
        "",
        "Retail demo domain with synthetic data (no real personal data). Timestamps are UTC. Money is",
        "`decimal(18,2)` in BRL with a dot as decimal separator.",
        "",
        "## Entities and relationships",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for contract in ENTITIES.values():
        for fk in contract.foreign_keys:
            label = f"{fk.column} ({fk.policy.value})"
            out.append(f'    {fk.parent.upper()} ||--o{{ {contract.name.upper()} : "{label}"')
    out += ["```", ""]
    for contract in ENTITIES.values():
        out += [
            f"## `{contract.name}`",
            "",
            contract.description,
            "",
            f"* Source format: **{contract.source_format.value}** · contract version {contract.version}",
            f"* Business key: `{', '.join(contract.business_key)}` · versions ordered by `{contract.version_column}`",
            f"* Silver partitioning: `{contract.silver_partition}`"
            if contract.silver_partition
            else "* Silver: unpartitioned",
        ]
        for fk in contract.foreign_keys:
            target = f"* `{fk.column}` -> `{fk.parent}.{fk.parent_column}`:"
            if fk.policy is FkPolicy.REJECT:
                out.append(f"{target} orphan records are rejected as `{fk.reason_code}`")
            else:
                out.append(f"{target} orphans are accepted and reported by a warning rule")
        out += ["", "| Column | Silver type | Required | Meaning |", "|---|---|---|---|"]
        for col in contract.columns:
            meaning = col.description + (
                f" Allowed: {', '.join(col.allowed_values)}." if col.allowed_values else ""
            )
            out.append(f"| `{col.name}` | {SPARK_TYPES[col.type].simpleString()} ({col.type.value}) | "
                       f"{'yes' if col.required else 'no'} | {meaning} |")  # fmt: skip
        for name, dtype, _ in DERIVED.get(contract.name, []):
            out.append(f"| `{name}` | {dtype.simpleString()} | derived | Derived in Silver from `sale_ts`. |")
        out.append("")
    out += [
        "## Lineage columns",
        "",
        "Bronze stores every business column as text plus these fields; Silver keeps a subset.",
        "",
        "| Column | Bronze | Silver | Meaning |",
        "|---|---|---|---|",
    ]
    silver_names = {f.name for f in SILVER_LINEAGE}
    names = [f.name for f in LINEAGE_FIELDS] + [
        f.name for f in SILVER_LINEAGE if f.name not in {x.name for x in LINEAGE_FIELDS}
    ]
    for name in names:
        in_bronze = "yes" if name in {f.name for f in LINEAGE_FIELDS} else "—"
        out.append(
            f"| `{name}` | {in_bronze} | {'yes' if name in silver_names else '—'} | {LINEAGE_DOC.get(name, '')} |"
        )
    out += [
        "",
        "## `silver._rejects`",
        "",
        "One row per rejected record, partitioned by `entity`; replaced per batch on re-runs.",
        "",
        "| Column | Meaning |",
        "|---|---|",
        "| `entity` | Entity of the record. |",
        "| `business_key` | Normalized business key as received (`|`-separated for composite keys). |",
        "| `rejection_reason` | First (primary) reason code. |",
        "| `rejection_reasons` | All reason codes, in evaluation order. |",
        "| `raw_record` | JSON of the source values, extra columns and corrupt text. |",
        "| `_batch_id`, `_batch_seq`, `_source_file`, `_record_hash` | Lineage. |",
        "| `_run_id`, `rejected_at` | Run that rejected it and when. |",
        "",
        GOLD_TABLES.strip(),
        "",
        "## Indicator catalog",
        "",
        "Also stored in the metadata table `metric_definitions` on every publication.",
        "",
        "| Metric | Formula | Filters | Sources |",
        "|---|---|---|---|",
    ]
    for metric in METRICS:
        out.append(f"| `{metric['metric_name']}` | `{metric['formula']}` | {metric['filters']} | "
                   f"{', '.join(metric['source_tables'])} |")  # type: ignore[arg-type]  # fmt: skip
    return "\n".join(out) + "\n"


def rule_catalog() -> str:
    from lakehouse.quality.rules import gold_rules, silver_rules

    rules = BusinessRules()
    out = [BEGIN, "", "### Row rules (Silver, per batch; violating records are rejected)", "",
           "| Rule id | Reason code | Category | Description |", "|---|---|---|---|"]  # fmt: skip
    for contract in ENTITIES.values():
        for reason, (rule_id, rule) in row_rule_catalog(contract, rules).items():
            out.append(f"| `{rule_id}` | `{reason}` | {rule.category} | {rule.description} |")
    out += [
        "",
        "### Dataset rules",
        "",
        "| Rule id | Severity | Category | Table | Description |",
        "|---|---|---|---|---|",
    ]
    for rule in [*silver_rules(), *gold_rules()]:
        out.append(f"| `{rule.rule_id}` | {rule.severity.value} | {rule.category.value} | `{rule.table_name}` | "
                   f"{rule.description} |")  # fmt: skip
    out += ["", END]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    targets = {ROOT / "docs" / "data_dictionary.md": data_dictionary()}
    quality = ROOT / "docs" / "data_quality.md"
    text = quality.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    targets[quality] = text[:start] + rule_catalog() + text[end:]
    stale = [
        p for p, content in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != content
    ]
    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)} (run scripts/gen_docs.py)")
        return 1 if stale else 0
    for path in stale:
        path.write_text(targets[path], encoding="utf-8")
        print(f"updated {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
